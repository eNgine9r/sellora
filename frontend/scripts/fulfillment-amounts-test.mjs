import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync('src/features/orders/lib/fulfillment-amounts.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const ctx = { exports: {} };
vm.runInNewContext(compiled, ctx);
const { fulfillmentAmount, isConfirmedCost, isNonNegativeAmount, isPositiveWholeQuantity } = ctx.exports;
assert.equal(fulfillmentAmount(null, 450), '450');
assert.equal(fulfillmentAmount(null, 900), '900');
assert.equal(fulfillmentAmount('125', 900), '125');
assert.equal(fulfillmentAmount('', 900), '');
assert.equal(isNonNegativeAmount(''), false);
assert.equal(isNonNegativeAmount('-1'), false);
assert.equal(isNonNegativeAmount('0'), true);
assert.equal(isNonNegativeAmount('125.50'), true);
assert.equal(isPositiveWholeQuantity('2'), true);
assert.equal(isPositiveWholeQuantity('1.5'), false);
assert.equal(isPositiveWholeQuantity(''), false);
assert.equal(isConfirmedCost(''), false);
assert.equal(isConfirmedCost(undefined), false);
assert.equal(isConfirmedCost('0'), true);
assert.equal(isConfirmedCost(0), true);
assert.equal(isConfirmedCost('120.50'), true);
assert.equal(isConfirmedCost('-1'), false);
assert.equal(isConfirmedCost('not a number'), false);
console.log('PASS fulfillment amount and quantity cases');
